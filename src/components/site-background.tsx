"use client"

import { useTheme } from "next-themes"
import { Threads } from "@/components/threads"

/**
 * ФОН ВСЕГО САЙТА — нити, расступающиеся под курсором.
 *
 * Раньше фон был только на первом экране, а остальные двенадцать панелей
 * стояли на ровном чёрном: сайт выглядел так, будто собран из разных
 * страниц. Теперь текстура одна на всю ленту и едет под всеми разделами.
 *
 * ПОЧЕМУ ОДИН ХОЛСТ, А НЕ ПО ОДНОМУ НА ПАНЕЛЬ
 *
 * Соблазн раздать каждой панели свой экземпляр верный только наполовину:
 * компонент сам останавливается, когда панель уходит из экрана, и
 * одновременно работает был бы один-два. Но покой — не главное. Главное
 * память: компонент держит кадровую текстуру во весь экран, и тринадцать
 * таких текстур — это около восьмидесяти мегабайт видеопамяти на пустом
 * месте. Один липкий слой вместо этого занимает столько же, сколько
 * раньше занимал один.
 *
 * ПОЧЕМУ НЕ «РАСТЯНУТЬ» ОДИН ХОЛСТ НА ВСЮ ЛЕНТУ
 *
 * Лента шириной во все тринадцать экранов — около 27 000 пикселей.
 * Шейдер строит узор в координатах своего кадра, а сам кадр ограничен
 * 1920 пикселями по длинной стороне: растянутая на всю ленту текстура
 * получила бы буфер 1920 на 68 и размазалась в горизонтальную полосу.
 * Без ограничения кадр занял бы около 106 МБ. Липкий слой во весь экран
 * даёт то же самое ощущение общего пространства без обеих этих цен.
 *
 * Слои: нити лежат под затемнением, а не поверх текста.
 */
const THREAD_COLORS = {
  dark: { color: "#5b7ba6", accentColor: "#a3c0e2" },
  light: { color: "#7e9ac0", accentColor: "#3d5f8c" },
} as const

export function SiteBackground() {
  const { resolvedTheme } = useTheme()

  // До гидрации тема неизвестна. Тёмная — запасной вариант: первым
  // показывается именно она, лишней перерисовки фона не будет.
  const palette = resolvedTheme === "light" ? THREAD_COLORS.light : THREAD_COLORS.dark

  return (
    <div aria-hidden className="absolute inset-0">
      <Threads
        {...palette}
        distance={0.9}
        lineCount={48}
        softness={2.4}
        thickness={0.55}
        amplitude={1.15}
        speed={0.35}
        opacity={0.75}
        fade={0.12}
        enableMouseInteraction
        parting={0.35}
      />

      {/*
        Затемнение. Оно одинаковое для всех панелей: разделы набраны
        плотно — словарик, чек-лист, памятка, — и текст должен читаться
        поверх текстуры одинаково везде. Полупрозрачность подобрана так,
        чтобы нити оставались заметными, но не мешали: на чёрном это
        примерно шесть процентов от белого, разница с фоном для текста
        в двадцать раз.
      */}
      <div className="absolute inset-0 bg-background/55" />
    </div>
  )
}