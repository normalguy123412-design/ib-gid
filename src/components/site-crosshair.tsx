"use client"

import { useTheme } from "next-themes"
import { Crosshair } from "@/components/crosshair"

/**
 * ПРИЦЕЛ НА САЙТЕ.
 *
 * Сам прицел лежит в crosshair.tsx — это чужой компонент из React Bits,
 * и он оставлен как есть. Здесь только настройки под этот сайт. Разделено
 * затем, чтобы обновление из реестра не затирало оформление, а правки
 * оформления не тонули в чужом коде.
 *
 * ЗАЧЕМ ОН ЗДЕСЬ
 *
 * Раздел про информационную безопасность читается как работа с прибором, и
 * прицел это поддерживает. Но он не только украшение: он наводится на
 * ссылки и кнопки и обводит их рамкой, поэтому видно, что нажимается, ещё
 * до нажатия. На панели, где больше десяти карточек, это экономит поиск
 * глазами — а заодно честно показывает, что кликабельно, а что нет.
 *
 * НАСКОЛЬКО ОН ЗАМЕТЕН
 *
 * Линии плотные (opacity 0.85) и чуть толще волоса (thickness 1.5): прицел
 * должен читаться сразу, а не угадываться. Но заметность не превращается в
 * миллиметровку — fade 0.78 гасит линии к краям экрана, у самых краёв они
 * прозрачны на 78%. Это подсказка рядом с курсором, а не сетка поверх всей
 * страницы. gap 8 оставляет пустоту вокруг самой точки: прицел показывает,
 * куда смотришь, и не закрывает то, на что смотришь.
 *
 * ЧТО ВЫКЛЮЧЕНО
 *
 * Координаты (showCoordinates): счётчик координат в углу — примета
 * инструмента для сборки макета, а не сайта. Он сообщает то, что и без
 * него видно, и занимает угол экрана.
 *
 * Пульс при клике (clickPulse), наоборот, включён: это единственный отклик
 * прицела на нажатие — от точки расходится кольцо. Он отвечает на действие
 * человека, а не живёт сам по себе.
 *
 * СЛАБЫЙ ПРИБОР
 *
 * Прицел на нём не отключается: это часть интерфейса, а не украшение, и без
 * него пропадёт подсказка о том, что кликабельно. Но плотность пикселей он
 * берёт меньше (см. src/lib/quality.ts) и потому стоит дешевле.
 *
 * ПОЧЕМУ ЦВЕТ ВЫБИРАЕТСЯ ПО ТЕМЕ
 *
 * Переменную темы сюда передать нельзя: компонент разбирает цвет через
 * ctx.fillStyle и прочитал бы «oklch(…)» как каналы RGB (подробнее в
 * crosshair.tsx). Поэтому цвет берётся по теме здесь и уходит готовым
 * значением. В светлой теме белый прицел пропал бы на белом фоне — ровно
 * та же ошибка, из-за которой в поле кода недавно был невидим курсор.
 *
 * Цвета при этом нейтральные. Смысловые цвета на сайте закреплены за
 * угрозами и защитой — красный и синий, — и прицел, окрашенный в один из
 * них, читался бы как оценка того, на что он наведён. Он инструмент, а не
 * суждение.
 */
export function SiteCrosshair() {
  const { resolvedTheme } = useTheme()
  const color = resolvedTheme === "light" ? "#3f3f46" : "#fafafa"

  return (
    <Crosshair
      color={color}
      thickness={1.5}
      opacity={0.85}
      lineStyle="dashed"
      gap={8}
      fade={0.78}
      smoothing={0.18}
      showCoordinates={false}
      targetEffect="lock"
      clickPulse
      hideCursor
    />
  )
}
