/**
 * Текущий год для копирайта.
 *
 * Считается на сервере при сборке, чтобы год не «прыгал» при гидрации
 * на клиенте. Раньше здесь стояла директива "use cache", но она требует
 * cacheComponents, а тот несовместим со статическим экспортом (output: export).
 * При статической генерации значение и так фиксируется в HTML навсегда.
 */
export function getCurrentYear() {
  return new Date().getFullYear()
}