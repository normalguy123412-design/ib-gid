/*
  УРОВЕНЬ КАЧЕСТВА — один на весь сайт.

  Задача: на слабом приборе сайт должен остаться читаемым и не дёргаться,
  а на обычном — не потерять ничего. Поэтому «слабый» определяется один
  раз, до первой отрисовки, и дальше весь код просто спрашивает ответ.

  КАК ЭТО РАБОТАЕТ

  Класс на <html> ставит маленький скрипт в layout.tsx — он выполняется
  до того, как отрисуется первая строка. Скрипт стоит в разметке, а не
  здесь, потому что решение нужно принять раньше, чем загрузится хоть
  один компонент: иначе первая секунда прошла бы в тяжёлом режиме, и
  слабый прибор успел бы дёрнуться.

  Здесь — только чтение ответа. Общий класс, а не React-состояние, ещё и
  потому, что он нужен и CSS: размытие по нему отключается в globals.css,
  без участия JavaScript.

  ЧТО СЧИТАЕТСЯ СЛАБЫМ

  Сигналы разные по весу, и одного мало. Совсем слабые вещи — экономный
  режим браузера (saveData), медленное соединение и одно-двухъядерные
  приборы — решают сами по себе. Четыре ядра и четыре гигабайта решают
  только вместе: порознь это середина, на которой сайт ещё идёт бодро.
  Так порог не срабатывает на обычном ноутбуке.

  Где браузер молчит (в Firefox нет deviceMemory), значение считается
  неизвестным и берётся запасное — восьмёрка. Неизвестное не должно
  ухудшать вид: не знаем — значит, считаем прибор обычным.
*/

const WEAK_CLASS = "quality-low"

/**
 * Слабый ли прибор. Ответ ставит скрипт из layout.tsx до первой
 * отрисовки, поэтому к моменту вызова он всегда готов.
 */
export function isWeakDevice(): boolean {
  return (
    typeof document !== "undefined" &&
    document.documentElement.classList.contains(WEAK_CLASS)
  )
}

/**
 * Предел плотности пикселей для холстов.

 * Плотность — множитель размера холста: при 2 каждый пиксель экрана
 * рисуется вчетверо большим числом точек. Для линий, которые едут под
 * курсором, этого не нужно: 1.5 не отличить на глаз, а работы вчетверо
 * меньше, чем при 2. На слабом приборе — ровно 1.

 * Ограничение не заменяет остальные: холсты ещё и останавливаются, когда
 * ничего не движется. Но там, где движение есть, экономия самая дешёвая
 * из возможных — без потери вида.
 */
export function pixelRatioLimit(strong = 1.5): number {
  return isWeakDevice() ? 1 : strong
}
